export type SpriteDef = {
  w: number
  h: number
  palette: string[]
  rows: string[]
}

/** '.' = transparent; digits index palette (0 unused / blank string). */
function S(
  w: number,
  h: number,
  palette: string[],
  rows: string[],
): SpriteDef {
  return { w, h, palette, rows }
}

